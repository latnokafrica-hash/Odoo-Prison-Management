export function generateBiometricHash(
  badgeNumber: string,
  timestamp: string,
  terminalId: string,
  minutiaePoints: number,
  finger: string
): string {
  const payload = `BIO_FP|${badgeNumber}|${timestamp}|${terminalId}|${minutiaePoints}pts|${finger}|SALT_SEC_58`;
  return sha256Sync(payload);
}

